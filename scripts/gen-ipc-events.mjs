// Single generator for the Rust → React JSON event bus.
//
// Reads shared/ipc_events.json (the one contract: wire names *and* payload
// shapes) and writes both committed outputs:
//   - src/ipc/generated/events.ts
//   - src-tauri/src/ipc/generated/events.rs
//
// The Rust output is committed rather than emitted from build.rs because the
// Rust CI job never installs Node. CI re-runs this script and diffs both
// paths, so contract drift is a build failure.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const RUST_TYPES = {
  bool: "bool",
  f32: "f32",
  f64: "f64",
  u32: "u32",
  u64: "u64",
  string: "String",
  str_static: "&'static str",
};

// u64 maps to `number`, not `bigint`: Tauri's JSON bus delivers a number and
// the replay store does arithmetic on it.
const TS_TYPES = {
  bool: "boolean",
  f32: "number",
  f64: "number",
  u32: "number",
  u64: "number",
  string: "string",
  str_static: "string",
};

// Field types that keep the payload struct `Copy` when every field is one.
const COPY_TYPES = new Set(["bool", "f32", "f64", "u32", "u64", "str_static"]);

const KEY_RE = /^[A-Z][A-Z0-9]*(_[A-Z0-9]+)*$/;
const WIRE_RE = /^[a-z][a-z0-9]*(-[a-z0-9]+)*$/;
const TYPE_RE = /^[A-Z][A-Za-z0-9]*$/;
const FIELD_RE = /^[a-z][a-z0-9]*(_[a-z0-9]+)*$/;

const camel = (snake) =>
  snake.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

/**
 * Validates the contract and returns its events sorted by constant key.
 * Throws on any malformed entry — this is the only validation gate.
 */
export function parseContract(contract) {
  if (
    contract === null ||
    typeof contract !== "object" ||
    Array.isArray(contract)
  ) {
    throw new Error("contract must be a JSON object");
  }
  const seenWire = new Set();
  const seenType = new Set();
  const events = [];
  for (const key of Object.keys(contract).sort()) {
    if (!KEY_RE.test(key)) {
      throw new Error(`${key}: constant keys must be SCREAMING_SNAKE_CASE`);
    }
    const entry = contract[key];
    if (entry === null || typeof entry !== "object" || Array.isArray(entry)) {
      throw new Error(`${key}: entry must be an object`);
    }
    if (!WIRE_RE.test(entry.name ?? "")) {
      throw new Error(`${key}: name must be a kebab-case wire name`);
    }
    if (seenWire.has(entry.name)) {
      throw new Error(`${key}: duplicate wire name ${entry.name}`);
    }
    seenWire.add(entry.name);
    if (!TYPE_RE.test(entry.type ?? "")) {
      throw new Error(`${key}: type must be a PascalCase payload name`);
    }
    if (seenType.has(entry.type)) {
      throw new Error(`${key}: duplicate payload type ${entry.type}`);
    }
    seenType.add(entry.type);
    if (!Array.isArray(entry.fields)) {
      throw new Error(`${key}: fields must be an array`);
    }
    const seenField = new Set();
    for (const field of entry.fields) {
      if (!FIELD_RE.test(field?.name ?? "")) {
        throw new Error(`${key}: field names must be snake_case Rust idents`);
      }
      if (seenField.has(field.name)) {
        throw new Error(`${key}: duplicate field ${field.name}`);
      }
      seenField.add(field.name);
      if (!Object.hasOwn(RUST_TYPES, field.type ?? "")) {
        throw new Error(
          `${key}.${field.name}: unknown field type ${field.type}`,
        );
      }
      if (field.optional && field.nullable) {
        throw new Error(
          `${key}.${field.name}: optional and nullable are exclusive`,
        );
      }
      if (field.list && (field.optional || field.nullable)) {
        throw new Error(
          `${key}.${field.name}: list fields cannot be optional or nullable`,
        );
      }
    }
    events.push({ key, ...entry });
  }
  return events;
}

const rustDoc = (lines, indent) =>
  (lines ?? []).map((line) => (line ? `${indent}/// ${line}` : `${indent}///`));

const tsDoc = (lines, indent) =>
  (lines ?? []).map((line) => (line ? `${indent}// ${line}` : `${indent}//`));

// `optional` drops the key from the wire entirely (TS `field?: T`); `nullable`
// keeps it as null (TS `field: T | null`). Both are `Option<T>` in Rust.
const rustFieldType = (field) => {
  const base = RUST_TYPES[field.type];
  if (field.list) return `Vec<${base}>`;
  if (field.optional || field.nullable) return `Option<${base}>`;
  return base;
};

const tsFieldType = (field) => {
  const base = TS_TYPES[field.type];
  if (field.list) return `${base}[]`;
  if (field.nullable) return `${base} | null`;
  return base;
};

const BACKTICK = String.fromCharCode(96);

/** Renders the body of src-tauri/src/ipc/generated/events.rs. */
export function renderRust(events) {
  const out = [
    "// Generated by scripts/gen-ipc-events.mjs from shared/ipc_events.json — do not edit.",
    "//",
    "// include!'d by src-tauri/src/ipc/events.rs rather than declared as a module,",
    "// so `cargo fmt` never walks it. It is still linted by `clippy -D warnings`.",
    "",
  ];
  for (const e of events) {
    out.push(`/// Wire name of the [${BACKTICK}${e.type}${BACKTICK}] event.`);
    out.push(`pub const ${e.key}: &str = ${JSON.stringify(e.name)};`);
    out.push("");
  }
  for (const e of events) {
    const copy = e.fields.every((f) => !f.list && COPY_TYPES.has(f.type));
    out.push(...rustDoc(e.doc, ""));
    out.push(`#[derive(Debug, Clone,${copy ? " Copy," : ""} Serialize)]`);
    out.push('#[serde(rename_all = "camelCase")]');
    if (e.fields.length === 0) {
      out.push(`pub struct ${e.type} {}`);
    } else {
      out.push(`pub struct ${e.type} {`);
      for (const f of e.fields) {
        out.push(...rustDoc(f.doc, "    "));
        if (f.optional) {
          out.push('    #[serde(skip_serializing_if = "Option::is_none")]');
        }
        out.push(`    pub ${f.name}: ${rustFieldType(f)},`);
      }
      out.push("}");
    }
    out.push("");
    out.push(`impl IpcEvent for ${e.type} {`);
    out.push(`    const NAME: &'static str = ${e.key};`);
    out.push("}");
    out.push("");
  }
  return out.join("\n");
}

/** Renders the body of src/ipc/generated/events.ts. */
export function renderTs(events) {
  const out = [
    "// Generated by scripts/gen-ipc-events.mjs from shared/ipc_events.json — do not edit.",
    "",
  ];
  for (const e of events) {
    out.push(`export const ${e.key} = ${JSON.stringify(e.name)} as const;`);
  }
  out.push("");
  for (const e of events) {
    out.push(...tsDoc(e.doc, ""));
    if (e.fields.length === 0) {
      out.push(`export type ${e.type}Payload = Record<string, never>;`);
      out.push("");
      continue;
    }
    out.push(`export type ${e.type}Payload = {`);
    for (const f of e.fields) {
      out.push(...tsDoc(f.doc, "  "));
      out.push(`  ${camel(f.name)}${f.optional ? "?" : ""}: ${tsFieldType(f)};`);
    }
    out.push("};");
    out.push("");
  }
  out.push(
    "// Wire name → payload shape. `subscribeIpcEvent` is generic over this map,",
  );
  out.push("// so a handler's payload type follows from the event name alone.");
  out.push("export type IpcEventPayloads = {");
  for (const e of events) {
    out.push(`  ${JSON.stringify(e.name)}: ${e.type}Payload;`);
  }
  out.push("};");
  out.push("");
  out.push("export type IpcEventName = keyof IpcEventPayloads;");
  out.push("");
  return out.join("\n");
}

const write = (path, body) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, body, "utf8");
  console.log(`wrote ${path}`);
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Reads the contract and writes both committed outputs. */
export function generate() {
  const contract = JSON.parse(
    readFileSync(join(root, "shared", "ipc_events.json"), "utf8"),
  );
  const events = parseContract(contract);
  write(join(root, "src", "ipc", "generated", "events.ts"), renderTs(events));
  write(
    join(root, "src-tauri", "src", "ipc", "generated", "events.rs"),
    renderRust(events),
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  generate();
}
